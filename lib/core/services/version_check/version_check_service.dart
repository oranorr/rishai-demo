abstract interface class VersionCheckService {
  /// Проверяет, требуется ли обновление для текущей платформы.
  ///
  /// Возвращает [true], если текущая версия приложения ниже
  /// минимально допустимой версии, указанной в конфигурации.
  /// Возвращает [false], если обновление не требуется или
  /// не удалось получить данные о версиях.
  Future<bool> isUpdateRequired();

  /// Возвращает URL магазина приложений для текущей платформы.
  ///
  /// Может вернуть null, если URL не найден или не удалось
  /// получить конфигурацию.
  Future<String?> getStoreUrl();
}
